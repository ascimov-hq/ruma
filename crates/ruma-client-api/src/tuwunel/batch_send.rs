//! `POST /_matrix/client/unstable/com.beeper.backfill/rooms/{roomId}/batch_send`
//!
//! Beeper's batch sending extension: insert many message events into a room
//! in one request, either at the end of the timeline (forward) or before the
//! start of it (backward). Called by mautrix bridgev2's `BatchSend` when the
//! homeserver advertises `com.beeper.batch_sending` in
//! `/_matrix/client/versions` `unstable_features`.

pub mod unstable {
    //! `/unstable/` (Beeper's `com.beeper.backfill` batch sending extension,
    //! no published MSC)

    use ruma_common::{
        MilliSecondsSinceUnixEpoch, OwnedEventId, OwnedRoomId, OwnedUserId,
        api::{auth_scheme::AppserviceToken, request, response},
        metadata,
    };
    use ruma_events::TimelineEventType;
    use serde::{Deserialize, Serialize};
    use serde_json::value::RawValue as RawJsonValue;

    metadata! {
        method: POST,
        rate_limited: false,
        authentication: AppserviceToken,
        history: {
            unstable => "/_matrix/client/unstable/com.beeper.backfill/rooms/{room_id}/batch_send",
        }
    }

    /// Request type for the `batch_send` endpoint.
    #[request]
    pub struct Request {
        /// The room to send the events to.
        #[ruma_api(path)]
        pub room_id: OwnedRoomId,

        /// Append the events to the end of the timeline instead of inserting
        /// them before the start of it.
        #[serde(default)]
        pub forward: bool,

        /// Append the events to the end of the timeline if the room doesn't
        /// contain any messages yet.
        #[serde(default)]
        pub forward_if_no_messages: bool,

        /// Send push notifications for forward events.
        #[serde(default)]
        pub send_notification: bool,

        /// Mark the last event in the batch as read by this user.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        pub mark_read_by: Option<OwnedUserId>,

        /// The events to send, ordered from oldest to newest.
        pub events: Vec<BatchSendEvent>,
    }

    /// Response type for the `batch_send` endpoint.
    #[response]
    pub struct Response {
        /// The IDs of the sent events, in the same order as the request.
        pub event_ids: Vec<OwnedEventId>,
    }

    /// A single event in a batch send request.
    #[derive(Clone, Debug, Deserialize, Serialize)]
    #[cfg_attr(not(ruma_unstable_exhaustive_types), non_exhaustive)]
    pub struct BatchSendEvent {
        /// The event ID to store the event under. Generated by the server if
        /// absent.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        pub event_id: Option<OwnedEventId>,

        /// The type of the event.
        #[serde(rename = "type")]
        pub event_type: TimelineEventType,

        /// The user sending the event.
        pub sender: OwnedUserId,

        /// The timestamp of the event.
        pub origin_server_ts: MilliSecondsSinceUnixEpoch,

        /// The content of the event.
        pub content: Box<RawJsonValue>,

        /// The state key of the event. State events are not allowed in batches.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        pub state_key: Option<String>,
    }

    impl Request {
        /// Creates a new `Request` with the given room ID and events.
        pub fn new(room_id: OwnedRoomId, events: Vec<BatchSendEvent>) -> Self {
            Self {
                room_id,
                forward: false,
                forward_if_no_messages: false,
                send_notification: false,
                mark_read_by: None,
                events,
            }
        }
    }

    impl Response {
        /// Creates a new `Response` with the given event IDs.
        pub fn new(event_ids: Vec<OwnedEventId>) -> Self {
            Self { event_ids }
        }
    }
}
